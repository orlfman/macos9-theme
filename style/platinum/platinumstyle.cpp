QColor gray(int v)
{
    return QColor(v, v, v);
}

const QColor Black(0, 0, 0), White(0xFF, 0xFF, 0xFF);
const QColor L1(0xCC, 0xCC, 0xFF), L2(0x99, 0x99, 0xFF), L3(0x66, 0x66, 0xCC), L4(0x33, 0x33, 0x99);
const QColor DisabledText = gray(0x77);

void hline(QPainter *p, int x0, int x1, int y, const QColor &c)
{
    if (x1 >= x0) {
        p->fillRect(QRect(x0, y, x1 - x0 + 1, 1), c);
    }
}

void vline(QPainter *p, int x, int y0, int y1, const QColor &c)
{
    if (y1 >= y0) {
        p->fillRect(QRect(x, y0, 1, y1 - y0 + 1), c);
    }
}

/*
 * Scroll bars, drawn vertically; horizontal bars are drawn through a
 * transposing transform (x <-> y), which keeps the top-left lighting.
 * Measured and checked pixel exact in the step 3 spike (docs/FINDINGS.md).
 */
constexpr int ScrollArrows = ScrollArrowBox * 2 - 1; // the boxes share an edge

void drawScrollArrow(QPainter *p, const QRect &r, bool up, bool pressed)
{
    const int x = r.x(), y = r.y(), w = r.width(), h = r.height();
    hline(p, x, x + w - 1, y, Black);
    hline(p, x, x + w - 1, y + h - 1, Black);
    vline(p, x, y, y + h - 1, Black);
    vline(p, x + w - 1, y, y + h - 1, Black);
    const QColor hi = pressed ? gray(0x55) : White;
    const QColor fill = pressed ? gray(0x77) : gray(0xDD);
    const QColor lo = pressed ? gray(0x99) : gray(0xBB);
    p->fillRect(QRect(x + 1, y + 1, w - 2, h - 2), fill);
    hline(p, x + 1, x + w - 3, y + 1, hi);
    vline(p, x + 1, y + 1, y + h - 3, hi);
    vline(p, x + w - 2, y + 2, y + h - 2, lo);
    hline(p, x + 2, x + w - 2, y + h - 2, lo);
    const int cx = x + w / 2 - 1;
    for (int i = 0; i < 4; ++i) {
        const int half = up ? i : 3 - i;
        hline(p, cx - half, cx + 1 + half, y + 6 + i, Black);
    }
}

void drawScrollThumb(QPainter *p, const QRect &r, bool pressed)
{
    const int x = r.x(), y = r.y(), w = r.width(), h = r.height();
    const QColor hi = pressed ? L2 : L1, fill = pressed ? L3 : L2, lo = pressed ? L4 : L3;
    hline(p, x, x + w - 1, y, Black);
    hline(p, x, x + w - 1, y + h - 1, Black);
    vline(p, x, y, y + h - 1, Black);
    vline(p, x + w - 1, y, y + h - 1, Black);
    p->fillRect(QRect(x + 1, y + 1, w - 2, h - 2), fill);
    vline(p, x + 1, y + 1, y + h - 3, hi);
    hline(p, x + 1, x + w - 3, y + 1, hi);
    p->fillRect(QRect(x + 1, y + 1, 1, 1), pressed ? L1 : gray(0xEE));
    vline(p, x + w - 2, y + 2, y + h - 2, lo);
    hline(p, x + 2, x + w - 2, y + h - 2, lo);
    if (h >= 12) {
        const int gy = y + (h - 8) / 2;
        for (int i = 0; i < 4; ++i) {
            hline(p, x + 5, x + 10, gy + 2 * i, L1);
            p->fillRect(QRect(x + 4, gy + 2 * i, 1, 1), gray(0xEE));
            hline(p, x + 5, x + 11, gy + 2 * i + 1, L4);
        }
    }
}

void drawScrollTrack(QPainter *p, const QRect &r)
{
    if (r.isEmpty()) {
        return;
    }
    const int x = r.x(), y = r.y(), w = r.width(), h = r.height();
    vline(p, x, y, y + h - 1, Black);
    vline(p, x + w - 1, y, y + h - 1, Black);
    p->fillRect(QRect(x + 1, y, w - 2, h), gray(0xAA));
    vline(p, x + 1, y, y + h - 1, gray(0x77));
    vline(p, x + 2, y, y + h - 1, gray(0x88));
    vline(p, x + w - 3, y, y + h - 1, gray(0xBB));
    vline(p, x + w - 2, y, y + h - 1, gray(0xCC));
    // The two shadow rows at its top (under the thumb or the bar's edge).
    hline(p, x + 1, x + w - 3, y, gray(0x77));
    if (h > 1) {
        hline(p, x + 3, x + w - 4, y + 1, gray(0x88));
    }
}

// Mac OS 9 had no right-to-left controls. Pop-up menus, spin boxes and
// group boxes in a right-to-left layout use Fusion's mirrored layout and
// drawing (consistently, so clicks match what's drawn) instead of a
// Platinum layout that doesn't mirror (AUDIT.md finding 19).
bool rtlFallback(QStyle::ComplexControl control, const QStyleOption *option)
{
    return option && option->direction == Qt::RightToLeft
        && (control == QStyle::CC_ComboBox || control == QStyle::CC_SpinBox || control == QStyle::CC_GroupBox);
}

// Layout of a vertical bar in r (rects for the parts).
struct ScrollLayout {
    QRect subLine, addLine, groove, slider, subPage, addPage;
};

ScrollLayout scrollLayout(const QRect &r, const QStyleOptionSlider *o, bool horizontal)
{
    // Work along the bar: length and thickness, then transpose back.
    const int length = horizontal ? r.width() : r.height();
    const int thick = horizontal ? r.height() : r.width();
    const int track = std::max(0, length - ScrollArrows);
    // 64-bit: maximum - minimum alone can overflow an int.
    const qint64 range = qint64(o->maximum) - o->minimum;
    const qint64 page = std::max(0, o->pageStep);
    const qint64 fit = range > 0 ? qint64(track) * page / (range + page) : track;
    const int len = int(std::clamp<qint64>(fit, std::min(ScrollThumbMin, track), track));
    const qint64 value = std::clamp<qint64>(o->sliderPosition, o->minimum, o->maximum);
    int pos = range > 0 ? int(qint64(track - len) * (value - o->minimum) / range) : 0;
    // A reversed bar (inverted appearance) runs backwards.
    if (o->upsideDown) {
        pos = track - len - pos;
    }
    auto make = [&](int along, int size) {
        return horizontal ? QRect(r.x() + along, r.y(), size, thick) : QRect(r.x(), r.y() + along, thick, size);
    };
    ScrollLayout l;
    l.subLine = make(track, ScrollArrowBox);
    l.addLine = make(track + ScrollArrowBox - 1, ScrollArrowBox);
    l.groove = make(0, track);
    l.slider = make(pos, len);
    l.subPage = make(0, pos);
    l.addPage = make(pos + len, track - pos - len);
    return l;
}

QRect transposed(const QRect &r)
{
    return QRect(r.y(), r.x(), r.height(), r.width());
}

/*
 * Check boxes and radio buttons: measured sprites; the states the captures
 * don't show are derived and marked as such.
 */
// The mark (check mark, radio dot): pixels black in `withMark` but not in
// `without`, so the shading around it isn't picked up.
bool isMark(const Sprite &withMark, const Sprite &without, int i)
{
    return withMark.data[i] == 0x000000 && without.data[i] != 0x000000;
}

// `base` with the mark from `withMark` on top, in `color`.
void drawWithMark(QPainter *p, int x, int y, const Sprite &base, const Sprite &withMark, const Sprite &without, const QColor &color)
{
    drawSprite(p, x, y, base);
    for (int r = 0; r < withMark.h; ++r) {
        for (int c = 0; c < withMark.w; ++c) {
            const int i = r * withMark.w + c;
            if (isMark(withMark, without, i)) {
                p->fillRect(QRect(x + c, y + r, 1, 1), color);
            }
        }
    }
}

/*
 * Sliders: groove from measured end pieces and a stretched middle column,
 * thumb sprites, ticks (white, black, #888888, under the thumb's center).
 * Vertical sliders are drawn transposed (derived, not captured).
 */
struct SliderLayout {
    QRect groove, handle, ticks;
};

SliderLayout sliderLayout(const QRect &r, const QStyleOptionSlider *o, bool horizontal)
{
    const int length = horizontal ? r.width() : r.height();
    const int travel = std::max(0, length - 2 * SliderInset - SliderThumbWidth);
    const int pos = QStyle::sliderPositionFromValue(o->minimum, o->maximum, o->sliderPosition, travel, o->upsideDown);
    auto make = [&](int along, int across, int alongSize, int acrossSize) {
        return horizontal ? QRect(r.x() + along, r.y() + across, alongSize, acrossSize)
                          : QRect(r.x() + across, r.y() + along, acrossSize, alongSize);
    };
    SliderLayout l;
    l.groove = make(0, SliderGrooveTop, length, SliderGrooveHeight);
    l.handle = make(SliderInset + pos, 0, SliderThumbWidth, SliderThumbHeight);
    l.ticks = make(0, SliderThumbHeight, length, SliderTickHeight);
    return l;
}

/*
 * Progress bars, column by column from the measured profiles (progress.h);
 * the barber pole from its measured stripe ramps.
 */
void progressColumn(QPainter *p, int x, int y, const int (&col)[14])
{
    for (int i = 0; i < 14; ++i) {
        putPixel(p, x, y + i, col[i]);
    }
}

void drawProgress(QPainter *p, const QRect &rect, qint64 value, qint64 minimum, qint64 maximum)
{
    using namespace Progress;
    const int W = rect.width();
    const int x0 = rect.x();
    const int y = rect.y() + (rect.height() - ProgressHeight) / 2;
    if (W < 6) {
        return;
    }
    progressColumn(p, x0, y, OuterLeft);
    progressColumn(p, x0 + 1, y, FrameLeft);
    progressColumn(p, x0 + W - 2, y, FrameRight);
    progressColumn(p, x0 + W - 1, y, OuterRight);
    const int inner = W - 4;
    const int left = x0 + 2;

    if (maximum <= minimum) {
        // Barber pole: 8 px Lavender / 8 px gray stripes slanting one pixel
        // per row, moving 4 px right every 0.2 s (progress-indeterminate-*.png).
        static const int lav[10] = {0x000088, 0x333399, 0x6666CC, 0x9999FF, 0xCCCCFF, 0x9999FF, 0x6666CC, 0x333399, 0x000088, 0x000055};
        static const int grey[10] = {0x555555, 0x777777, 0xAAAAAA, 0xBBBBBB, 0xFFFFFF, 0xDDDDDD, 0xBBBBBB, 0x999999, 0x777777, 0x555555};
        // 20 px/s; PLATINUM_BARBER_PHASE pins it for the render checks.
        static const int pinned = qEnvironmentVariableIsSet("PLATINUM_BARBER_PHASE") ? qEnvironmentVariableIntValue("PLATINUM_BARBER_PHASE") : -1;
        const int phase = pinned >= 0 ? pinned % 16 : int((QDateTime::currentMSecsSinceEpoch() / 50) % 16);
        for (int c = 0; c < inner; ++c) {
            for (int i : {0, 1, 12, 13}) {
                putPixel(p, left + c, y + i, TroughMid[i]);
            }
            for (int r = 0; r < 10; ++r) {
                const bool isGrey = (((c - r - phase) % 16) + 16) % 16 < 8;
                putPixel(p, left + c, y + 2 + r, isGrey ? grey[r] : lav[r]);
            }
        }
        return;
    }

    const qint64 range = maximum - minimum;
    const int fill = int(std::clamp<qint64>((value - minimum) * inner / range, 0, inner));
    // Fill columns: start, start, middle..., end, end, end.
    const int *ends[] = {FillStart0, FillStart1, FillEnd0, FillEnd1, FillEnd2};
    for (int c = 0; c < fill; ++c) {
        const int *col;
        if (fill >= 5) {
            col = c == 0 ? FillStart0 : c == 1 ? FillStart1 : c == fill - 3 ? FillEnd0 : c == fill - 2 ? FillEnd1 : c == fill - 1 ? FillEnd2 : FillMid;
        } else {
            col = ends[5 - fill + c];
        }
        progressColumn(p, left + c, y, *reinterpret_cast<const int(*)[14]>(col));
    }
    // Then the divider, the trough's 2-column shadow, the trough, and its
    // last column.
    for (int c = fill; c < inner; ++c) {
        const int k = c - fill;
        const int(&col)[14] = c == inner - 1 && k > 2 ? TroughRight : k == 0 ? Divider : k == 1 ? TroughShadow0 : k == 2 ? TroughShadow1 : TroughMid;
        progressColumn(p, left + c, y, col);
    }
}

bool isNorth(QTabBar::Shape shape)
{
    return shape == QTabBar::RoundedNorth || shape == QTabBar::TriangularNorth;
}

// The pane under a north tab bar: from the tab bar's last 3 rows down.
QRect tabPane(const QStyleOptionTabWidgetFrame *tw)
{
    QRect r = tw->rect;
    r.setTop(r.top() + tw->tabBarSize.height() - TabPaneOverlap);
    return r;
}

// One tab, row by row from the measured edges (tabs.h): background, slanted
// left edge, fill, slanted right edge. The last 3 rows lie on the pane's top
// edge; a normal tab repeats it there, the current one opens into the pane.
void drawTab(QPainter *p, const QRect &r, const Tabs::Shape &s)
{
    for (int row = 0; row < TabHeight && row < r.height(); ++row) {
        const int y = r.y() + row;
        const Tabs::Edge &l = s.left[row];
        const Tabs::Edge &rt = s.right[row];
        const int from = r.x() + l.offset + l.length;
        const int to = r.right() - rt.offset - rt.length;
        if (to >= from) {
            p->fillRect(QRect(from, y, to - from + 1, 1), QColor::fromRgb(QRgb(s.fill[row])));
        }
        for (int i = 0; i < l.length; ++i) {
            putPixel(p, r.x() + l.offset + i, y, l.pixels[i]);
        }
        for (int i = 0; i < rt.length; ++i) {
            putPixel(p, r.right() - rt.offset - i, y, rt.pixels[i]);
        }
    }
}

// Menus (docs/REFERENCE.md "Menus"): a black outline with a 1 px #222222
// drop shadow right and bottom (starting 2 px in), inside it a 1 px bevel
// (white top/left, #999999 right/bottom; the two corners where they meet
// are the #DDDDDD fill). Items run edge to edge inside the black line, so
// the first and last item cover the bevel rows.
void drawMenuPanel(QPainter *p, const QRect &r)
{
    const int x = r.x(), y = r.y(), w = r.width(), h = r.height();
    if (w < 6 || h < 6) {
        return;
    }
    p->fillRect(QRect(x + w - 1, y + 2, 1, h - 2), gray(0x22));
    p->fillRect(QRect(x + 2, y + h - 1, w - 2, 1), gray(0x22));
    p->fillRect(QRect(x, y, w - 1, h - 1), Black);
    const QRect in(x + 1, y + 1, w - 3, h - 3);
    p->fillRect(in, gray(0xDD));
    p->fillRect(QRect(in.left(), in.top(), in.width() - 1, 1), White);
    p->fillRect(QRect(in.left(), in.top(), 1, in.height() - 1), White);
    p->fillRect(QRect(in.right(), in.top() + 1, 1, in.height() - 1), gray(0x99));
    p->fillRect(QRect(in.left() + 1, in.bottom(), in.width() - 1, 1), gray(0x99));
}

// One item's slice of the menu bevel: light left column and top row,
// dark right column and bottom row, the two corners where they meet in the
// fill color; the top / bottom row only where the item covers the menu's
// bevel rows (first / last item). Highlighted items use it in Lavender
// (#6666CC, #333399, #000088), measured on a first item
// (menu-view-checked.png); the last item's bottom row follows the panel's
// pattern. Pop-up lists draw it in gray for every item, since Qt fills
// their items with the window color first.
void drawMenuItemBevel(QPainter *p, const QRect &r, bool first, bool last, const QColor &light, const QColor &fill, const QColor &dark)
{
    p->fillRect(r, fill);
    p->fillRect(QRect(r.left(), r.top(), 1, r.height() - (last ? 1 : 0)), light);
    p->fillRect(QRect(r.right(), r.top() + (first ? 1 : 0), 1, r.height() - (first ? 1 : 0)), dark);
    if (first) {
        p->fillRect(QRect(r.left(), r.top(), r.width() - 1, 1), light);
    }
    if (last) {
        p->fillRect(QRect(r.left() + 1, r.bottom(), r.width() - 1, 1), dark);
    }
}

void drawMenuCheck(QPainter *p, int x, int y, const QColor &color)
{
    for (int row = 0; row < Menu::CheckHeight; ++row) {
        for (int col = 0; col < Menu::CheckWidth; ++col) {
            if (const int a = Menu::Check[row][col]) {
                QColor c(color);
                c.setAlpha(a);
                p->fillRect(QRect(x + col, y + row, 1, 1), c);
            }
        }
    }
}

// Submenu arrow: a solid triangle 6 wide, 11 tall, pointing right.
void drawMenuArrow(QPainter *p, int x, int y, const QColor &color)
{
    for (int row = 0; row < MenuArrowHeight; ++row) {
        const int w = row <= MenuArrowHeight / 2 ? row + 1 : MenuArrowHeight - row;
        p->fillRect(QRect(x, y + row, w, 1), color);
    }
}

// Menu bar background, or a title (highlighted: the Lavender bevel, top
// and bottom rows only). The last row is the bar's black line.
void drawMenuBarBackground(QPainter *p, const QRect &r, bool highlighted)
{
    p->fillRect(r, highlighted ? QColor(0x33, 0x33, 0x99) : gray(0xDD));
    p->fillRect(QRect(r.x(), r.y(), r.width(), 1), highlighted ? QColor(0x66, 0x66, 0xCC) : White);
    p->fillRect(QRect(r.x(), r.bottom() - 1, r.width(), 1), highlighted ? QColor(0x00, 0x00, 0x88) : gray(0x99));
    p->fillRect(QRect(r.x(), r.bottom(), r.width(), 1), Black);
}

bool menuHasShortcuts(const QWidget *widget)
{
    if (const auto *menu = qobject_cast<const QMenu *>(widget)) {
        const auto actions = menu->actions();
        for (const QAction *a : actions) {
            if (a->isVisible() && (a->text().contains(QLatin1Char('\t')) || !a->shortcut().isEmpty())) {
                return true;
            }
        }
    }
    return false;
}

// A text field (docs/REFERENCE.md "Text field"): in a rect with a 1 px
// margin, a sunken 1 px edge (#888888 top/left, white bottom/right, the
// two corners where they meet left out), then a black line and the white
// inside. Focused: the 2 px #6666CC ring fills the margin and the edge,
// minus its four corner pixels.
void drawField(QPainter *p, const QRect &r, bool focused, const QColor &base)
{
    const int x0 = r.left(), y0 = r.top(), x1 = r.right(), y1 = r.bottom();
    if (r.width() < 8 || r.height() < 8) {
        return;
    }
    if (focused) {
        const QColor ring(0x66, 0x66, 0xCC);
        p->fillRect(QRect(x0 + 1, y0, r.width() - 2, 1), ring);
        p->fillRect(QRect(x0 + 1, y1, r.width() - 2, 1), ring);
        p->fillRect(QRect(x0, y0 + 1, r.width(), r.height() - 2), ring);
    } else {
        p->fillRect(QRect(x0 + 1, y0 + 1, r.width() - 3, 1), gray(0x88));
        p->fillRect(QRect(x0 + 1, y0 + 1, 1, r.height() - 3), gray(0x88));
        p->fillRect(QRect(x1 - 1, y0 + 2, 1, r.height() - 3), White);
        p->fillRect(QRect(x0 + 2, y1 - 1, r.width() - 3, 1), White);
    }
    const QRect black = r.adjusted(2, 2, -2, -2);
    p->fillRect(black, Black);
    p->fillRect(black.adjusted(1, 1, -1, -1), base);
}

bool hasFieldFrame(const QStyleOption *option)
{
    const auto *f = qstyleoption_cast<const QStyleOptionFrame *>(option);
    return f && f->lineWidth > 0;
}

// A list / text area frame: the text field's sunken edge and black line,
// without its margin (derived: no capture of a Platinum list box frame;
// Standard File's list in dialog-file-open.png is a plain black line).
void drawSunkenFrame(QPainter *p, const QRect &r)
{
    const int x0 = r.left(), y0 = r.top(), x1 = r.right(), y1 = r.bottom();
    p->fillRect(QRect(x0, y0, r.width() - 1, 1), gray(0x88));
    p->fillRect(QRect(x0, y0, 1, r.height() - 1), gray(0x88));
    p->fillRect(QRect(x1, y0 + 1, 1, r.height() - 1), White);
    p->fillRect(QRect(x0 + 1, y1, r.width() - 1, 1), White);
    p->setPen(Black);
    p->setBrush(Qt::NoBrush);
    p->drawRect(r.adjusted(1, 1, -2, -2));
}

// Bevel buttons. Toolbar buttons (auto-raise) use the small square bevel
// from Mac Help's toolbar; other tool buttons the large rounded one from
// the Monitors control panel (both states measured). The small one's
// pressed look isn't captured: its colors are mapped the way the large
// one's change (white highlight -> #555555, fill -> #666666, shadow ->
// #777777), the #666666 / #333333 outline kept.
void drawBevel(QPainter *p, const QRect &r, bool small, bool pressed)
{
    if (!small) {
        drawNineSlice(p, r, pressed ? Slices::BevelPressed : Slices::BevelNormal);
        return;
    }
    if (!pressed) {
        drawNineSlice(p, r, Slices::ToolNormal);
        return;
    }
    NineSlice<2> s = Slices::ToolNormal;
    auto map = [](int v) {
        switch (v) {
        case 0xFFFFFF:
            return 0x555555;
        case 0xCCCCCC:
            return 0x666666;
        case 0x888888:
            return 0x777777;
        default:
            return v;
        }
    };
    for (auto *corner : {&s.tl, &s.tr, &s.bl, &s.br}) {
        for (auto &row : *corner) {
            for (int &v : row) {
                v = map(v);
            }
        }
    }
    for (auto *edge : {&s.top, &s.bottom, &s.left, &s.right}) {
        for (int &v : *edge) {
            v = map(v);
        }
    }
    s.fill = map(s.fill);
    drawNineSlice(p, r, s);
}

// Tooltips as Mac OS 9 help balloons (help-balloon.png), without the tail
// (a Qt tooltip doesn't point at anything): white, a 1 px black outline on
// the top and left, 2 px on the right and bottom, rounded corners. Rows
// are drawn as spans: the outline pixels at each end, white between.
// Top-left, bottom-left and bottom-right corners measured; the top-right
// one is under the tail in the capture, so it mirrors the top-left with
// the 2 px right edge.
void drawBalloon(QPainter *p, const QRect &r)
{
    const int x0 = r.left(), x1 = r.right(), y0 = r.top(), y1 = r.bottom();
    if (r.width() < 16 || r.height() < 16) {
        p->fillRect(r, White);
        return;
    }
    // {from, to} offsets: left spans from x0, right spans back from x1.
    static const int tl[6][2] = {{0, 0}, {3, 5}, {2, 3}, {1, 2}, {1, 1}, {0, 1}};
    static const int bl[6][2] = {{0, 0}, {0, 0}, {2, 4}, {1, 2}, {1, 1}, {0, 1}};
    static const int tr[7][2] = {{0, 0}, {6, 3}, {4, 2}, {3, 1}, {2, 1}, {2, 0}, {1, 0}};
    static const int br[7][2] = {{0, 0}, {0, 0}, {6, 2}, {4, 1}, {3, 1}, {2, 0}, {2, 0}};
    for (int y = y0; y <= y1; ++y) {
        const int t = y - y0, b = y1 - y;
        if (t == 0) {
            p->fillRect(QRect(x0 + 5, y, (x1 - 6) - (x0 + 5) + 1, 1), Black);
            continue;
        }
        if (b == 0 || b == 1) {
            const int from = x0 + (b == 0 ? 5 : 3), to = x1 - (b == 0 ? 5 : 3);
            p->fillRect(QRect(from, y, to - from + 1, 1), Black);
            continue;
        }
        int l0 = 0, l1 = 0, r0 = 1, r1 = 0;
        if (t <= 5) {
            l0 = tl[t][0], l1 = tl[t][1];
        } else if (b <= 5) {
            l0 = bl[b][0], l1 = bl[b][1];
        }
        if (t <= 6) {
            r0 = tr[t][0], r1 = tr[t][1];
        } else if (b <= 6) {
            r0 = br[b][0], r1 = br[b][1];
        }
        p->fillRect(QRect(x0 + l0, y, l1 - l0 + 1, 1), Black);
        p->fillRect(QRect(x1 - r0, y, r0 - r1 + 1, 1), Black);
        const int w0 = x0 + l1 + 1, w1 = x1 - r0 - 1;
        if (w1 >= w0) {
            p->fillRect(QRect(w0, y, w1 - w0 + 1, 1), White);
        }
    }
}

