#!/bin/bash
# Regenerates style/platinum/slices.h and style/platinum/sprites.h from the
# reference captures (needs reference/, the private capture repo). Every value
# is a measured gray level; see docs/REFERENCE.md for what each one is.
set -euo pipefail
root=$(dirname "$(dirname "$(readlink -f "$0")")")
cd "$root"
ref=reference
out=style/platinum

{
    echo "// Generated by tools/gen-style-data.sh from the reference captures (measured"
    echo "// gray levels). Regenerate rather than edit. -1 = not drawn."
    echo "#pragma once"
    echo '#include "nineslice.h"'
    echo "namespace Platinum::Slices {"
    py() { python3 -I tools/nineslice.py "$@" 2> /dev/null; }
    # Push buttons, 20 px tall (K=4). The pressed capture's label area and
    # bottom middle have the pointer in them: skipped, the edges are read in
    # the middle column.
    py $ref/button-default-pressed.png 617 513 70 20 4 PushNormal --bg FFFFFF --skip 6,4,63,15
    py $ref/button-push-pressed.png 641 469 70 20 4 PushPressed --bg FFFFFF --skip 6,4,63,19
    py $ref/dialog-file-open.png 851 335 80 20 4 PushDisabled --bg DDDDDD --skip 6,4,73,15
    # Default buttons with their 3 px ring, 26 px tall (K=8). The ring is the
    # same in dialog-file-open.png and button-push-pressed.png (checked).
    py $ref/dialog-file-open.png 848 435 86 26 8 PushDefault --bg DDDDDD --skip 9,7,76,18
    py $ref/button-default-pressed.png 697 510 78 26 8 PushDefaultPressed --bg FFFFFF --skip 9,7,68,25
    echo "} // namespace Platinum::Slices"
} > "$out/slices.h"

{
    echo "// Generated by tools/gen-style-data.sh from the reference captures (measured"
    echo "// gray levels). Regenerate rather than edit. -1 = not drawn."
    echo "#pragma once"
    echo '#include "sprite.h"'
    echo "namespace Platinum::Sprites {"
    sp() { python3 -I tools/sprite.py "$@"; }
    sp $ref/controls-general-controls.png 550 327 14 12 CheckOff --bg DDDDDD
    sp $ref/controls-general-controls.png 550 280 14 12 CheckOn --bg DDDDDD
    sp $ref/controls-memory.png 553 511 14 12 CheckOnDisabled --bg DDDDDD
    sp $ref/controls-general-controls.png 553 534 12 12 RadioOff --bg DDDDDD
    sp $ref/controls-general-controls.png 553 552 12 12 RadioOn --bg DDDDDD
    sp $ref/controls-monitors.png 732 405 12 12 RadioOffDisabled --bg DDDDDD
    # Pressed: the capture's pointer touches the bottom edge (check box) and
    # the lower-right rim (radio); fix_outline below copies the unpressed
    # outline into those pixels.
    sp $ref/checkbox-pressed.png 550 327 14 12 CheckOffPressedRaw --bg DDDDDD
    sp $ref/radio-pressed.png 553 534 12 12 RadioOffPressedRaw --bg DDDDDD
    echo "} // namespace Platinum::Sprites"
} > "$out/sprites.h.tmp"

python3 -I - "$out/sprites.h.tmp" "$out/sprites.h" << 'EOF'
import re, sys
text = open(sys.argv[1]).read()

def table(name):
    m = re.search(r"const Sprite %s = \{(\d+), (\d+), \{(.*?)\}\};" % name, text, re.S)
    w, h = int(m[1]), int(m[2])
    vals = re.findall(r"-1|0x[0-9A-F]{6}", m[3])
    return w, h, vals, m

def fix(raw, ref, rows):
    """Copy ref's outline (its -1 and black pixels) into raw on the given rows."""
    w, h, rv, m = table(raw)
    _, _, fv, _ = table(ref)
    for r in rows:
        for c in range(w):
            i = r * w + c
            if fv[i] in ("-1", "0x000000"):
                rv[i] = fv[i]
    name = raw.replace("Raw", "")
    body = ",\n    ".join(", ".join(rv[r * w:(r + 1) * w]) for r in range(h))
    return f"// {name}: {raw} with {ref}'s outline on rows {list(rows)} (pointer in the capture)\n" \
           f"const Sprite {name} = {{{w}, {h}, {{\n    {body},\n}}}};\n"

extra = fix("CheckOffPressedRaw", "CheckOff", range(10, 12)) + fix("RadioOffPressedRaw", "RadioOff", range(8, 12))
text = text.replace("} // namespace Platinum::Sprites", extra + "} // namespace Platinum::Sprites")
open(sys.argv[2], "w").write(text)
EOF
rm "$out/sprites.h.tmp"
echo "wrote $out/slices.h and $out/sprites.h"
