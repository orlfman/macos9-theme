#!/bin/bash
# Regenerates style/platinum/{slices,sprites,progress,tabs,menu}.h from the
# reference captures (needs reference/, the private capture repo). Every value
# is a measured gray level; see docs/REFERENCE.md for what each one is.
set -euo pipefail
root=$(dirname "$(dirname "$(readlink -f "$0")")")
cd "$root"
ref=reference
out=style/platinum

{
    echo "// Generated by tools/gen-style-data.sh from the reference captures (measured"
    echo "// gray levels). Regenerate rather than edit. -1 = not drawn."
    echo "#pragma once"
    echo '#include "nineslice.h"'
    echo "namespace Platinum::Slices {"
    py() { python3 -I tools/nineslice.py "$@" 2> /dev/null; }
    # Push buttons, 20 px tall (K=4). The pressed capture's label area and
    # bottom middle have the pointer in them: skipped, the edges are read in
    # the middle column.
    py $ref/button-default-pressed.png 617 513 70 20 4 PushNormal --bg FFFFFF --skip 6,4,63,15
    py $ref/button-push-pressed.png 641 469 70 20 4 PushPressed --bg FFFFFF --skip 6,4,63,19
    py $ref/dialog-file-open.png 851 335 80 20 4 PushDisabled --bg DDDDDD --skip 6,4,73,15
    # Default buttons with their 3 px ring, 26 px tall (K=8). The ring is the
    # same in dialog-file-open.png and button-push-pressed.png (checked).
    py $ref/dialog-file-open.png 848 435 86 26 8 PushDefault --bg DDDDDD --skip 9,7,76,18
    py $ref/button-default-pressed.png 697 510 78 26 8 PushDefaultPressed --bg FFFFFF --skip 9,7,68,25
    # Pop-up menu bodies, 20 px tall; only the part left of the arrow box
    # (its own sprite) is measured, so the right edge here gets covered.
    py $ref/appearance-2-appearance.png 591 257 159 20 4 PopupBody --bg EEEEEE --skip 4,2,158,17
    py $ref/appearance-4-desktop.png 710 451 173 20 4 PopupBodyDisabled --bg EEEEEE --skip 4,2,172,17
    # Tab pane: black outline + 2 px bevel around #EEEEEE. In the Appearance
    # control panel it fills the window, so its black lines coincide with
    # the window frame's. Only the left 5 columns are read for the top edge
    # (the tabs cover the rest of it); the interior holds the panel's
    # controls and is skipped.
    py $ref/appearance-1-themes.png 469 235 466 280 4 TabPane --bg DDDDDD --skip 5,0,461,275
    # Finder list header sections, 21 px tall (K=2): normal ("Date
    # Modified") and the sorted column ("Name"). A section's right side is
    # the next section's left line, so neither has a right edge of its own
    # (the sorted one has its dark shadow there).
    py $ref/disclosure-triangles.png 343 154 149 21 2 HeaderSection --skip 3,3,145,17
    py $ref/disclosure-triangles.png 105 154 238 21 2 HeaderSorted --skip 3,3,234,17
    echo "} // namespace Platinum::Slices"
} > "$out/slices.h"

{
    echo "// Generated by tools/gen-style-data.sh from the reference captures (measured"
    echo "// gray levels). Regenerate rather than edit. -1 = not drawn."
    echo "#pragma once"
    echo '#include "sprite.h"'
    echo "namespace Platinum::Sprites {"
    sp() { python3 -I tools/sprite.py "$@"; }
    sp $ref/controls-general-controls.png 550 327 14 12 CheckOff --bg DDDDDD
    sp $ref/controls-general-controls.png 550 280 14 12 CheckOn --bg DDDDDD
    sp $ref/controls-memory.png 553 511 14 12 CheckOnDisabled --bg DDDDDD
    sp $ref/controls-general-controls.png 553 534 12 12 RadioOff --bg DDDDDD
    sp $ref/controls-general-controls.png 553 552 12 12 RadioOn --bg DDDDDD
    sp $ref/controls-monitors.png 732 405 12 12 RadioOffDisabled --bg DDDDDD
    # Pop-up arrow boxes: the right 22 columns, from the divider to the edge.
    sp $ref/appearance-2-appearance.png 749 257 22 20 PopupArrow --bg EEEEEE
    # Pressed: both open-menu captures have the pointer over this box, in
    # different places; merged below (columns 0-1 from no-hover, the rest
    # from popup-open).
    sp $ref/popup-open.png 749 298 22 20 PopupArrowPressedA --bg EEEEEE
    sp $ref/popup-open-no-hover.png 749 298 22 20 PopupArrowPressedB --bg EEEEEE
    sp $ref/appearance-4-desktop.png 882 451 22 20 PopupArrowDisabled --bg EEEEEE
    # Slider thumbs (15x16, pointing down at the ticks).
    sp $ref/controls-general-controls.png 764 438 15 16 SliderThumb --bg DDDDDD
    sp $ref/slider-pressed.png 764 438 15 16 SliderThumbPressed --bg DDDDDD
    sp $ref/controls-memory.png 675 483 15 16 SliderThumbDisabled --bg DDDDDD
    # Slider grooves (7 rows with the outer lines; disabled ones have none):
    # left end, one middle column (stretched), right end.
    sp $ref/controls-general-controls.png 726 441 3 7 GrooveLeft --bg DDDDDD
    sp $ref/controls-general-controls.png 740 441 1 7 GrooveMid --bg DDDDDD
    sp $ref/controls-general-controls.png 814 441 3 7 GrooveRight --bg DDDDDD
    sp $ref/controls-memory.png 672 486 3 7 GrooveLeftDisabled --bg DDDDDD
    sp $ref/controls-memory.png 700 486 1 7 GrooveMidDisabled --bg DDDDDD
    sp $ref/controls-memory.png 809 486 3 7 GrooveRightDisabled --bg DDDDDD
    # Pressed: the capture's pointer touches the bottom edge (check box) and
    # the lower-right rim (radio); fix_outline below copies the unpressed
    # outline into those pixels.
    # Little arrows (spin box buttons), the Appearance control panel's
    # rounded 22x20 kind, next to the Fonts tab's size fields.
    sp $ref/appearance-3-fonts-clean.png 878 349 22 20 SpinArrows --bg EEEEEE
    # Disclosure triangles, 17x17 boxes in Finder list rows (#DDDDDD, the
    # sorted column): closed, open, pressed (closed, its fill #333399 and
    # no shadow; the pointer covers the lower right, fixed below).
    sp $ref/disclosure-triangles.png 108 194 17 17 TriangleClosed --bg DDDDDD
    sp $ref/disclosure-triangles.png 108 270 17 17 TriangleOpen --bg DDDDDD
    sp $ref/triangle-pressed.png 108 213 17 17 TrianglePressedRaw --bg DDDDDD
    sp $ref/checkbox-pressed.png 550 327 14 12 CheckOffPressedRaw --bg DDDDDD
    sp $ref/radio-pressed.png 553 534 12 12 RadioOffPressedRaw --bg DDDDDD
    echo "} // namespace Platinum::Sprites"
} > "$out/sprites.h.tmp"

python3 -I - "$out/sprites.h.tmp" "$out/sprites.h" << 'EOF'
import re, sys
text = open(sys.argv[1]).read()

def table(name):
    m = re.search(r"const Sprite %s = \{(\d+), (\d+), \{(.*?)\}\};" % name, text, re.S)
    w, h = int(m[1]), int(m[2])
    vals = re.findall(r"-1|0x[0-9A-F]{6}", m[3])
    return w, h, vals, m

def fix(raw, ref, rows):
    """Copy ref's outline (its -1 and black pixels) into raw on the given rows."""
    w, h, rv, m = table(raw)
    _, _, fv, _ = table(ref)
    for r in rows:
        for c in range(w):
            i = r * w + c
            if fv[i] in ("-1", "0x000000"):
                rv[i] = fv[i]
    name = raw.replace("Raw", "")
    body = ",\n    ".join(", ".join(rv[r * w:(r + 1) * w]) for r in range(h))
    return f"// {name}: {raw} with {ref}'s outline on rows {list(rows)} (pointer in the capture)\n" \
           f"const Sprite {name} = {{{w}, {h}, {{\n    {body},\n}}}};\n"

def merge(a, b, b_cols, name):
    """Sprite `name`: `a`, with columns `b_cols` taken from `b`."""
    w, h, av, _ = table(a)
    _, _, bv, _ = table(b)
    out = [bv[i] if (i % w) in b_cols else av[i] for i in range(w * h)]
    body = ",\n    ".join(", ".join(out[r * w:(r + 1) * w]) for r in range(h))
    return f"// {name}: {a} with columns {sorted(b_cols)} from {b} (pointer in each capture)\n" \
           f"const Sprite {name} = {{{w}, {h}, {{\n    {body},\n}}}};\n"

def clear(raw, rows, cols):
    """Sprite raw without "Raw": the given pixels set to -1 (pointer)."""
    w, h, rv, m = table(raw)
    for r in rows:
        for c in cols:
            rv[r * w + c] = "-1"
    name = raw.replace("Raw", "")
    body = ",\n    ".join(", ".join(rv[r * w:(r + 1) * w]) for r in range(h))
    return f"// {name}: {raw} without rows {list(rows)}, columns {list(cols)} (pointer in the capture)\n" \
           f"const Sprite {name} = {{{w}, {h}, {{\n    {body},\n}}}};\n"

extra = clear("TrianglePressedRaw", range(11, 17), range(9, 17)) + fix("CheckOffPressedRaw", "CheckOff", range(10, 12)) + fix("RadioOffPressedRaw", "RadioOff", range(8, 12)) \
    + merge("PopupArrowPressedA", "PopupArrowPressedB", {0, 1}, "PopupArrowPressed")
text = text.replace("} // namespace Platinum::Sprites", extra + "} // namespace Platinum::Sprites")
open(sys.argv[2], "w").write(text)
EOF
rm "$out/sprites.h.tmp"

# Determinate progress bar, column by column (14 rows: outer AA line, black
# frame, 10 inner rows, black frame, outer white line), from the 55 % frame.
python3 -I - "$ref/progress-determinate-55.png" "$out/progress.h" << 'EOF'
import sys
from PIL import Image
im = Image.open(sys.argv[1]).convert("RGB")
cols = {
    "OuterLeft": 590, "FrameLeft": 591, "FillStart0": 592, "FillStart1": 593,
    "FillMid": 650, "FillEnd0": 690, "FillEnd1": 691, "FillEnd2": 692,
    "Divider": 693, "TroughShadow0": 694, "TroughShadow1": 695, "TroughMid": 730,
    "TroughRight": 775, "FrameRight": 776, "OuterRight": 777,
}
with open(sys.argv[2], "w") as f:
    f.write("// Generated by tools/gen-style-data.sh from progress-determinate-55.png\n")
    f.write("// (measured gray levels). Regenerate rather than edit. 14 rows each,\n")
    f.write("// top to bottom: outer line, frame, 10 inner rows, frame, outer line.\n")
    f.write("#pragma once\nnamespace Platinum::Progress {\n")
    for name, x in cols.items():
        vals = []
        for y in range(276, 290):
            p = im.getpixel((x, y))
            vals.append(f"0x{(p[0] << 16) | (p[1] << 8) | p[2]:06X}")
        f.write(f"constexpr int {name}[14] = {{{', '.join(vals)}}}; // x={x}\n")
    f.write("} // namespace Platinum::Progress\n")
EOF
# Menu check mark (anti-aliased black on #DDDDDD) as a 9x8 coverage mask,
# so it can be drawn black on the menu or white on the #333399 highlight.
python3 -I - "$ref/menu-view-checked.png" "$out/menu.h" "$ref/popup-open.png" << 'EOF'
import sys
from PIL import Image
im = Image.open(sys.argv[1]).convert("RGB")
hl = Image.open(sys.argv[3]).convert("RGB")
x0, y0 = 113, 56  # "as List" row (item y=52-67), 4 px right of the menu's black edge
rows = []
for y in range(y0, y0 + 8):
    vals = []
    for x in range(x0, x0 + 9):
        v = im.getpixel((x, y))[0]
        vals.append(str(round((0xDD - min(v, 0xDD)) * 255 / 0xDD)))
    rows.append(", ".join(vals))
with open(sys.argv[2], "w") as f:
    f.write("// Generated by tools/gen-style-data.sh from menu-view-checked.png at\n")
    f.write(f"// ({x0},{y0}). Regenerate rather than edit. Coverage 0-255 (from the\n")
    f.write("// anti-aliased black glyph on #DDDDDD). Needs redrawing before any public\n")
    f.write("// release (it's a rendered font glyph; see PLAN.md).\n")
    f.write("#pragma once\nnamespace Platinum::Menu {\n")
    f.write("constexpr int CheckWidth = 9, CheckHeight = 8;\nconstexpr unsigned char Check[8][9] = {\n")
    for r in rows:
        f.write("    {" + r + "},\n")
    f.write("};\n")
    # On the #333399 highlight Mac OS 9 blends the white mark itself
    # (peaking at #FEFEFE), so that state is a plain sprite from
    # popup-open.png ("Purple", current and highlighted).
    f.write("// The check mark on the highlight, from popup-open.png at (595,303).\n")
    f.write("constexpr int CheckHighlighted[8][9] = {\n")
    for y in range(303, 311):
        f.write("    {" + ", ".join("0x%02X%02X%02X" % hl.getpixel((x, y)) for x in range(595, 604)) + "},\n")
    f.write("};\n} // namespace Platinum::Menu\n")
EOF
python3 -I tools/tabs.py > /dev/null
echo "wrote $out/slices.h, $out/sprites.h, $out/progress.h, $out/tabs.h and $out/menu.h"
