#!/usr/bin/env python3
"""Measure Platinum tabs row by row and print them as C++ tables.

A tab is 24 rows: 21 rows of tab, then the 3 rows of the pane's top edge
that it shares (black line, #CCCCCC, white). Each row has a slanted left
edge, a fill, and a slanted right edge. For every row this records:

  left offset   columns from the tab's left x to its first pixel
  left pattern  the edge pixels from there until the fill starts
  fill          the row's fill: the first color that repeats three times
                after the edge pattern
  right offset / right pattern, the same from the tab's right x inwards

Usage: tabs.py   (paths and coordinates are in the TABS table below)
Writes style/platinum/tabs.h. Needs reference/ (the private capture repo).
"""

import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
REF = ROOT / "reference"
ROWS = 24
BG = (0xDD, 0xDD, 0xDD)  # the window behind the tab row

# (state, side): capture, tab's left x, right x (bottom row), top y.
# Normal edges come from the first tab's left edge and the last tab's right
# edge (no neighbor next to them); tabs touch only on their bottom row.
TABS = {
    ("Normal", "left"): ("appearance-2-appearance.png", 474, 546, 214),
    ("Normal", "right"): ("appearance-2-appearance.png", 839, 910, 214),
    ("Current", "left"): ("appearance-1-themes.png", 474, 546, 214),
    ("Current", "right"): ("appearance-6-options.png", 839, 910, 214),
    ("Pressed", "left"): ("tab-pressed.png", 1082, 1143, 204),
    # The pointer in this capture sits inside the tab's lower right part and
    # on the pane below it, not on the edge pixels this reads.
    ("Pressed", "right"): ("tab-pressed.png", 1082, 1143, 204),
}


def rgb(p):
    return (p[0] << 16) | (p[1] << 8) | p[2]


def measure(state, side):
    name, left, right, top = TABS[(state, side)]
    im = Image.open(REF / name).convert("RGB")
    rows = []
    for r in range(ROWS):
        y = top + r
        step = 1 if side == "left" else -1
        x = left if side == "left" else right
        # skip the window background ...
        offset = 0
        while im.getpixel((x, y)) == BG and offset < 16:
            offset += 1
            x += step
        # ... then the edge pattern runs until the fill: the first color
        # that shows up three times in a row (labels can start right after
        # the edge, so the row's most common color isn't reliable)
        pattern = []
        while True:
            p = [im.getpixel((x + i * step, y)) for i in range(3)]
            if p[0] == p[1] == p[2]:
                fill = p[0]
                break
            pattern.append(rgb(p[0]))
            if len(pattern) > 8:
                sys.exit(f"{state} {side} row {r}: no fill after 8 pixels")
            x += step
        rows.append((offset, pattern, rgb(fill)))
    return rows


def main():
    out = ["// Generated by tools/tabs.py from the reference captures (measured gray",
           "// levels). Regenerate rather than edit.",
           "#pragma once",
           "namespace Platinum::Tabs {",
           "struct Edge { int offset; int length; int pixels[8]; };",
           "struct Shape { Edge left[24]; Edge right[24]; int fill[24]; };"]
    cache = {}

    def get(state, side):
        if (state, side) not in cache:
            cache[(state, side)] = measure(state, side)
        return cache[(state, side)]

    for state in ("Normal", "Current", "Pressed"):
        lrows = get(state, "left")
        rrows = get(state, "right")
        fills = [row[2] for row in lrows]

        def edges(rows):
            items = []
            for offset, pattern, _ in rows:
                px = ", ".join(f"0x{v:06X}" for v in pattern) or "0"
                items.append(f"{{{offset}, {len(pattern)}, {{{px}}}}}")
            return "{" + ", ".join(items) + "}"

        out.append(f"// {state}: left edge from {TABS[(state, 'left')][0]}, right edge from {TABS[(state, 'right')][0]}")
        out.append(f"constexpr Shape {state} = {{")
        out.append(f"    {edges(lrows)},")
        out.append(f"    {edges(rrows)},")
        out.append("    {" + ", ".join(f"0x{v:06X}" for v in fills) + "},")
        out.append("};")
        mism = [r for r in range(ROWS) if lrows[r][2] != rrows[r][2]]
        if mism:
            print(f"warning: {state}: fill differs between the two sources on rows {mism}", file=sys.stderr)
    out.append("} // namespace Platinum::Tabs")
    (ROOT / "style/platinum/tabs.h").write_text("\n".join(out) + "\n")
    print("wrote style/platinum/tabs.h")


if __name__ == "__main__":
    main()
